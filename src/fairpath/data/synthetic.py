"""Synthetic look-alike data so anyone can clone the repo and run everything.

Method: a Gaussian copula fitted separately within each outcome class.

1. Every column is mapped to normal scores through its empirical CDF (categorical
   columns are first turned into integer codes ordered by frequency).
2. We estimate the correlation of those normal scores, draw new correlated normals,
   and map each column back through its own empirical quantile function.

This keeps the marginal distributions, the pairwise dependence and the link between
features and the outcome, while no synthetic row is a copy of a real student.
The output has exactly the same columns and file format as the original CSV.

It is *not* a privacy mechanism with formal guarantees (that would need differential
privacy). Both source datasets are already public and anonymised; the synthetic copy
exists for convenience and CI, not to protect secrets. Results quoted anywhere in the
project come from the real data unless they are explicitly marked SYNTHETIC.
"""

from __future__ import annotations

import logging

import numpy as np
import pandas as pd
from scipy import stats

from fairpath.config import DatasetSpec

log = logging.getLogger(__name__)

SYNTHETIC_BANNER = "SYNTHETIC DATA -- generated by fairpath, not real students"


def _encode(col: pd.Series) -> tuple[np.ndarray, list | None]:
    if pd.api.types.is_numeric_dtype(col):
        return col.to_numpy(dtype=float), None
    cats = col.astype(str).value_counts().index.tolist()
    mapping = {c: i for i, c in enumerate(cats)}
    return col.astype(str).map(mapping).to_numpy(dtype=float), cats


def _normal_scores(x: np.ndarray, rng: np.random.Generator) -> np.ndarray:
    # random tie-breaking so discrete columns still get a continuous copula
    ranks = stats.rankdata(x + rng.uniform(0, 1e-6, size=len(x)), method="ordinal")
    return stats.norm.ppf(ranks / (len(x) + 1))


def _sample_class(block: pd.DataFrame, n: int, rng: np.random.Generator) -> pd.DataFrame:
    enc, cats = {}, {}
    for c in block.columns:
        enc[c], cats[c] = _encode(block[c])
    Z = np.column_stack([_normal_scores(enc[c], rng) for c in block.columns])
    corr = np.corrcoef(Z, rowvar=False)
    corr = np.nan_to_num(corr, nan=0.0)
    np.fill_diagonal(corr, 1.0)
    # shrink a little towards identity: keeps the matrix PD and avoids overfitting small classes
    corr = 0.95 * corr + 0.05 * np.eye(len(corr))
    draws = rng.multivariate_normal(np.zeros(len(corr)), corr, size=n)
    u = stats.norm.cdf(draws)

    out = {}
    for j, c in enumerate(block.columns):
        sorted_vals = np.sort(enc[c])
        idx = np.clip((u[:, j] * len(sorted_vals)).astype(int), 0, len(sorted_vals) - 1)
        vals = sorted_vals[idx]
        if cats[c] is not None:
            out[c] = [cats[c][int(v)] for v in vals]
        else:
            orig = block[c]
            if pd.api.types.is_integer_dtype(orig):
                out[c] = vals.astype(int)
            else:
                out[c] = vals
    return pd.DataFrame(out)


def make_synthetic(
    raw: pd.DataFrame, spec: DatasetSpec, n: int | None = None, seed: int = 42
) -> pd.DataFrame:
    """Return a synthetic frame with the same schema as ``raw``."""
    rng = np.random.default_rng(seed)
    n = n or len(raw)
    tcol = spec.target.source
    if spec.target.threshold is not None:
        # numeric target (G3): stratify on pass/fail so the class balance is preserved
        strata = (pd.to_numeric(raw[tcol]) >= spec.target.threshold).astype(int)
    else:
        strata = raw[tcol].astype(str)

    parts = []
    props = strata.value_counts(normalize=True)
    counts = rng.multinomial(n, props.to_numpy())
    for (level, _), k in zip(props.items(), counts, strict=True):
        block = raw[strata == level].reset_index(drop=True)
        if k == 0:
            continue
        parts.append(_sample_class(block, int(k), rng))
    synth = pd.concat(parts, ignore_index=True)
    synth = synth.sample(frac=1.0, random_state=seed).reset_index(drop=True)
    synth = synth[raw.columns]
    log.info("Generated %d synthetic rows for %s", len(synth), spec.name)
    return synth
