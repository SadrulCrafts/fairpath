"""Collect stage outputs into one overview (for the dashboard), figures and docs/RESULTS.md.

docs/RESULTS.md is generated -- every number in it is read from reports/*.json, which in
turn were written by the pipeline. Nothing is typed in by hand.
"""

from __future__ import annotations

import logging
from pathlib import Path
from typing import Any

from fairpath import __version__
from fairpath.config import PROJECT_ROOT, Settings, load_dataset_spec
from fairpath.models import MODEL_LABELS
from fairpath.pipeline import figures
from fairpath.pipeline.common import now_iso, read_json, write_json

log = logging.getLogger(__name__)


def _ci(m: dict) -> str:
    if m.get("lo") is None:
        return f"{m['value']:.3f}"
    return f"{m['value']:.3f} [{m['lo']:.3f}, {m['hi']:.3f}]"


def dataset_overview(base: Path, name: str) -> dict[str, Any] | None:
    d = base / name
    if not (d / "final_model.json").exists():
        return None
    spec = load_dataset_spec(name)
    final = read_json(d / "final_model.json")
    bench = read_json(d / "benchmark.json")
    study = read_json(d / "fairness_study.json")
    pre = read_json(d / "preflight.json")
    prim = spec.primary_sensitive
    tm = final["test_metrics"]["deployed"]
    fair = final["fairness"][prim]
    best = bench["best_model"]
    rec = study["recommendations"].get(prim, {}).get(best)
    blk = study["summary"].get(prim, {}).get(best, {"methods": []})
    by = {e["method"]: e for e in blk["methods"]}
    blind_effect = (
        {
            k: {"eodds": by[k]["eodds"]["mean"], "spd": by[k]["spd"]["mean"], "f1": by[k]["f1"]["mean"]}
            for k in ("baseline", "blind", "reweighing", "blind_reweighing")
            if k in by
        }
        if by
        else None
    )
    return {
        "dataset": name,
        "title": spec.title,
        "short_title": spec.short_title,
        "description": spec.description,
        "licence": spec.licence,
        "citation": spec.citation,
        "source_url": spec.source_url,
        "n": final["provenance"]["n"],
        "n_test": final["n_test"],
        "data_source": final["provenance"]["data_source"],
        "at_risk_label": spec.target.at_risk_label,
        "model": final["model"],
        "model_label": final["model_label"],
        "threshold": final["deployed"]["threshold"],
        "test": {k: tm[k] for k in ("roc_auc", "pr_auc", "brier", "ece", "f1", "precision", "recall")},
        "baseline_test": {k: final["test_metrics"]["baseline"][k] for k in ("roc_auc", "f1", "recall")},
        "calibration": {k: final["calibration"][k] for k in ("method", "test_ece_before", "test_ece_after")},
        "conformal": final["conformal"],
        "primary_axis": prim,
        "primary_label": spec.sensitive[prim].label,
        "fairness": {
            "deployed": {k: fair["deployed"]["gaps"][k] for k in ("spd", "eodds", "tpr_gap", "fpr_gap")},
            "baseline": {k: fair["baseline"]["gaps"][k] for k in ("spd", "eodds", "tpr_gap", "fpr_gap")},
            "groups": fair["deployed"]["groups"],
        },
        "preflight": {
            axis: {
                "label": v["label"],
                "v1": v["v1"]["verdict"],
                "v1_passed": v["v1"]["passed"],
                "v2": v["v2"]["verdict"],
                "v2_code": v["v2"]["verdict_code"],
            }
            for axis, v in pre["axes"].items()
        },
        "benchmark_best": best,
        "benchmark_best_label": MODEL_LABELS[best],
        "benchmark_auc": {r["model"]: r["roc_auc"] for r in bench["summary"]},
        "recommendation": rec,
        "blind_effect": blind_effect,
        "degenerate_methods": [e["label"] for e in blk["methods"] if e.get("degenerate")],
        "sensitive_rank": final["sensitive_rank"],
        "leakage_check": final["leakage_check"],
        "programme_audit": (
            (final["programme_audit"] or {}).get("weighted_flag_gap") if final["programme_audit"] else None
        ),
    }


def results_markdown(ov: dict[str, Any], base: Path, repro: dict | None) -> str:
    L: list[str] = []
    L.append("# Results\n")
    L.append(
        f"_Generated by `fairpath report` on {now_iso()} (fairpath {__version__}). Every number below is read "
        "from `reports/*.json`; nothing is typed by hand. Results are on the **real UCI data** unless a "
        "section says SYNTHETIC._\n"
    )
    for name, o in ov["datasets"].items():
        d = base / name
        bench = read_json(d / "benchmark.json")
        study = read_json(d / "fairness_study.json")
        final = read_json(d / "final_model.json")
        pre = read_json(d / "preflight.json")
        L.append(f"\n## {o['title']}\n")
        L.append(
            f"Development split n = {bench['n_dev']}, held-out test n = {o['n_test']}. Positive class: "
            f"**{o['at_risk_label'].lower()}**.\n"
        )
        L.append("\n### Model comparison (5x5 CV on the development split)\n")
        L.append(
            "| Model | ROC-AUC [95% CI] | PR-AUC | Brier | F1 (rate-matched) | SPD (rate-matched) | EOdds (rate-matched) |"
        )
        L.append("|---|---|---|---|---|---|---|")
        for r in bench["summary"]:
            L.append(
                f"| {r['label']} | {r['roc_auc']['mean']:.3f} [{r['roc_auc']['lo']:.3f}, {r['roc_auc']['hi']:.3f}] | "
                f"{r['pr_auc']['mean']:.3f} | {r['brier']['mean']:.3f} | {r['f1_rm']['mean']:.3f} | "
                f"{r['spd_rm']['mean']:.3f} | {r['eodds_rm']['mean']:.3f} |"
            )
        L.append(
            "\nCIs use the Nadeau-Bengio correction for overlapping CV folds. Differences from the best model "
            "(Holm-corrected corrected-t p-values): "
            + ", ".join(
                f"{MODEL_LABELS[c['model']]} p={c['corrected_t']['p_holm']:.3f}" for c in bench["comparisons"]
            )
            + ".\n"
        )

        L.append("\n### Deployed model on the held-out test set\n")
        t = final["test_metrics"]
        L.append(
            f"{o['model_label']}, blind to {o['primary_label'].lower()}, trained with Reweighing, "
            f"{final['calibration']['method']} calibration, flag threshold {o['threshold']:.2f}.\n"
        )
        L.append("| Metric | Deployed | Unmitigated aware baseline |")
        L.append("|---|---|---|")
        for k in ("roc_auc", "pr_auc", "brier", "ece", "f1", "precision", "recall"):
            L.append(f"| {k} | {_ci(t['deployed'][k])} | {_ci(t['baseline'][k])} |")
        c = final["conformal"]["test"]
        L.append(
            f"\nConformal prediction sets (target {1 - final['conformal']['alpha']:.0%}): empirical coverage "
            f"{c['coverage']:.3f}, {c['uncertain_share']:.1%} of test students get the two-outcome 'uncertain' set.\n"
        )

        L.append("\n### Fairness on the held-out test set\n")
        for axis, fb in final["fairness"].items():
            g_dep, g_base = fb["deployed"]["gaps"], fb["baseline"]["gaps"]
            L.append(f"\n**{fb['label']}**\n")
            L.append("| Gap | Deployed [95% CI] | perm. p | Baseline [95% CI] |")
            L.append("|---|---|---|---|")
            for k in ("spd", "tpr_gap", "fpr_gap", "eodds", "ppv_gap"):
                pp = g_dep[k].get("perm_p")
                L.append(
                    f"| {g_dep[k]['label']} | {_ci(g_dep[k])} | {'' if pp is None else f'{pp:.3f}'} | {_ci(g_base[k])} |"
                )
            if fb["deployed"]["warnings"]:
                L.append("\n> " + " ".join(fb["deployed"]["warnings"]))

        L.append("\n### Mitigation study (5x2 CV, development split)\n")
        for axis, models in study["summary"].items():
            for model, blk in models.items():
                L.append(f"\n**{axis} / {blk['model_label']}**\n")
                L.append(
                    "| Method | Stage | F1 | ROC-AUC | SPD | EOdds | p(EOdds vs baseline, Holm) | Pareto |"
                )
                L.append("|---|---|---|---|---|---|---|---|")
                for e in blk["methods"]:
                    p = e.get("tests", {}).get("eodds", {}).get("p_holm")
                    L.append(
                        f"| {e['label']} | {e['stage']} | {e['f1']['mean']:.3f} | {e['roc_auc']['mean']:.3f} | "
                        f"{e['spd']['mean']:.3f} | {e['eodds']['mean']:.3f} | "
                        f"{'' if p is None else f'{p:.3f}'} | {'yes' if e['pareto'] else ''} |"
                    )

        L.append("\n### Pre-flight check\n")
        L.append("| Axis | v1 (thesis) checks | v1 verdict | v2 checks | v2 verdict |")
        L.append("|---|---|---|---|---|")
        for axis, v in pre["axes"].items():
            v1 = "; ".join(
                f"{c['name']}: {c['value']} ({'pass' if c['passed'] else 'fail'})" for c in v["v1"]["checks"]
            )
            v2 = "; ".join(
                f"{c['name']}: {c['value']} ({'pass' if c['passed'] else 'fail'})" for c in v["v2"]["checks"]
            )
            L.append(f"| {v['label']} | {v1} | {v['v1']['verdict']} | {v2} | {v['v2']['verdict']} |")

        sr = final["sensitive_rank"]
        L.append(
            f"\n### Where does the bias come from?\n\nIn the aware model, `{sr['feature']}` ranks "
            f"{sr['shap_rank']} of {sr['n_features']} by mean |SHAP| and {sr['perm_rank']} of {sr['n_features']} "
            f"by held-out permutation importance ({sr['perm_importance']:+.4f} +/- {sr['perm_sd']:.4f} AUC).\n"
        )
        if final["leakage_check"]:
            lc = final["leakage_check"]
            L.append(
                f"\nLeakage sensitivity: dropping {', '.join(lc['dropped'])} changes out-of-fold AUC from "
                f"{lc['auc_with']:.3f} to {lc['auc_without']:.3f}.\n"
            )
        if final["programme_audit"]:
            pa = final["programme_audit"]
            L.append(
                f"\nWithin-programme audit: enrolment-weighted male-minus-female flag-rate gap "
                f"{pa['weighted_flag_gap']:+.3f} against an outcome gap of {pa['weighted_outcome_gap']:+.3f}.\n"
            )

    if repro:
        L.append("\n## Thesis reproduction\n")
        L.append(repro["note"] + "\n")
        L.append("| Table | Dataset | Model | Metric | Thesis | Re-computed | Status |")
        L.append("|---|---|---|---|---|---|---|")
        for r in repro["comparison"]:
            L.append(
                f"| {r['table']} | {r['dataset']} | {MODEL_LABELS.get(r['model'], r['model'])} | {r['metric']} | "
                f"{r['thesis']:.3f} | {r['reproduced']:.3f} | {r['status']} |"
            )
    return "\n".join(L) + "\n"


def run(settings: Settings, synthetic: bool = False) -> dict[str, Any]:
    base = settings.path("reports") / ("synthetic" if synthetic else "")
    datasets = {}
    for name in settings.datasets:
        o = dataset_overview(base, name)
        if o:
            datasets[name] = o
    repro_path = base / "thesis_reproduction.json"
    repro = read_json(repro_path) if repro_path.exists() else None
    repro_counts = None
    if repro:
        repro_counts = {
            s: sum(1 for r in repro["comparison"] if r["status"] == s) for s in ("match", "close", "differs")
        }
        t51 = [r for r in repro["comparison"] if r["table"] == "5.1"]
        repro_counts["table_5_1_match"] = sum(1 for r in t51 if r["status"] == "match")
        repro_counts["table_5_1_total"] = len(t51)
    ov = {
        "version": __version__,
        "generated_at": now_iso(),
        "synthetic": synthetic,
        "datasets": datasets,
        "thesis_reproduction": repro_counts,
    }
    write_json(base / "overview.json", ov)

    fig_dir = PROJECT_ROOT / "docs" / "figures" if not synthetic else base / "figures"
    for name, o in datasets.items():
        spec = load_dataset_spec(name)
        final = read_json(base / name / "final_model.json")
        study = read_json(base / name / "fairness_study.json")
        prim = spec.primary_sensitive
        figures.pareto(
            study,
            prim,
            o["benchmark_best"],
            f"{spec.short_title}: fairness vs accuracy "
            f"({spec.sensitive[prim].label.lower()}, {o['benchmark_best_label']})",
            fig_dir / f"pareto_{name}.png",
        )
        figures.group_bars(
            final,
            prim,
            f"{spec.short_title}: who gets flagged, and who gets caught",
            fig_dir / f"groups_{name}.png",
        )
        figures.calibration(
            final, f"{spec.short_title}: calibration (test)", fig_dir / f"calibration_{name}.png"
        )
        figures.shap_bars(
            final,
            {f.name: f.label for f in spec.features},
            f"{spec.short_title}: what drives the risk score",
            fig_dir / f"shap_{name}.png",
        )
    if repro:
        figures.thesis_scatter(repro, fig_dir / "thesis_reproduction.png")
    if not synthetic:
        (PROJECT_ROOT / "docs" / "RESULTS.md").write_text(results_markdown(ov, base, repro), encoding="utf-8")
        log.info("wrote docs/RESULTS.md")
    return ov
